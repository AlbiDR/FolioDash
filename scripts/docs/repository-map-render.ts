// Renders docs/architecture/repository-map.md from the files themselves: the folder tree and the layer
// dependency diagram. It is pure, so `npm run docs:map` writes it and `npm run verify:docs` checks it is current.

import ts from "typescript";
import { layer } from "../verify/repository-policy.ts";

const NODE_OF = (name: string): string => (name.startsWith("feature:") ? "features" : name);
const ORDER = [
  "core",
  "applications",
  "adapters",
  "server",
  "shared",
  "presentation",
  "features",
  "app",
  "service-worker",
];

/** Which layer imports which, from the real relative imports of production source (tests and CSS excluded). */
export function layerEdges(files: readonly string[], read: (file: string) => string): [string, string][] {
  const known = new Set(files);
  const edges = new Set<string>();
  for (const file of files) {
    if (!/^src\/.*\.tsx?$/.test(file) || /\.test\.tsx?$/.test(file) || file.endsWith(".d.ts")) continue;
    const from = layer(file);
    if (from === null) continue;
    const ast = ts.createSourceFile(file, read(file), ts.ScriptTarget.Latest, true);
    const visit = (node: ts.Node): void => {
      let specifier: string | undefined;
      if ((ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) && node.moduleSpecifier !== undefined) {
        if (ts.isStringLiteral(node.moduleSpecifier)) specifier = node.moduleSpecifier.text;
      } else if (ts.isCallExpression(node) && node.expression.kind === ts.SyntaxKind.ImportKeyword) {
        const [argument] = node.arguments;
        if (argument !== undefined && ts.isStringLiteral(argument)) specifier = argument.text;
      }
      if (specifier?.startsWith(".")) {
        const base = [...file.split("/").slice(0, -1), ...specifier.split("/")].reduce<string[]>((path, part) => {
          if (part === "..") path.pop();
          else if (part !== ".") path.push(part);
          return path;
        }, []);
        const target = [base.join("/") + ".ts", base.join("/") + ".tsx"].find((candidate) => known.has(candidate));
        const to = target === undefined ? null : layer(target);
        if (to !== null && NODE_OF(to) !== NODE_OF(from)) edges.add(`${NODE_OF(from)}|${NODE_OF(to)}`);
      }
      ts.forEachChild(node, visit);
    };
    visit(ast);
  }
  const rank = (name: string): number => ORDER.indexOf(name);
  return [...edges]
    .map((edge) => edge.split("|") as [string, string])
    .sort((a, b) => rank(a[0]) - rank(b[0]) || rank(a[1]) - rank(b[1]));
}

interface Folder {
  readonly children: Map<string, Folder>;
}

function tree(directories: readonly string[], root: string, depth: number): string[] {
  const top: Folder = { children: new Map() };
  for (const directory of directories) {
    if (directory !== root && !directory.startsWith(`${root}/`)) continue;
    const parts = directory.slice(root.length).split("/").filter(Boolean).slice(0, depth);
    let node = top;
    for (const part of parts) {
      if (!node.children.has(part)) node.children.set(part, { children: new Map() });
      node = node.children.get(part) ?? node;
    }
  }
  const lines = [`${root}/`];
  const walk = (node: Folder, prefix: string): void => {
    const names = [...node.children.keys()].sort();
    names.forEach((name, index) => {
      const last = index === names.length - 1;
      lines.push(`${prefix}${last ? "└── " : "├── "}${name}/`);
      walk(node.children.get(name) ?? node, `${prefix}${last ? "    " : "│   "}`);
    });
  };
  walk(top, "");
  return lines;
}

export function renderMap(files: readonly string[], read: (file: string) => string): string {
  const directories = [
    ...new Set(
      files.flatMap((file) =>
        file
          .split("/")
          .slice(0, -1)
          .map((_, i, p) => p.slice(0, i + 1).join("/")),
      ),
    ),
  ].sort();
  const edges = layerEdges(files, read);
  const sections: [string, number][] = [
    ["src", 6],
    ["tests", 3],
    ["scripts", 2],
    ["config", 1],
    ["docs", 2],
  ];
  const parts = [
    "# Repository map",
    "",
    "Generated by `npm run docs:map`; do not edit. `npm run verify:docs` fails when it is out of date. The folder tree lists directories only, and the diagram shows which layer imports which, taken from the real imports of production source.",
    "",
    "## Layer dependencies",
    "",
    "An arrow means some file in the first layer imports a file in the second. The rules that allow or forbid each arrow are in [CleanStack](cleanstack.md) section 4.1 and are enforced by `npm run verify:repository`.",
    "",
    "```mermaid",
    "flowchart LR",
    ...edges.map(([from, to]) => `  ${from.replace("-", "_")}[${from}] --> ${to.replace("-", "_")}[${to}]`),
    "```",
    "",
    "## Folders",
    "",
  ];
  for (const [root, depth] of sections) parts.push("```text", ...tree(directories, root, depth), "```", "");
  return `${parts.join("\n").trimEnd()}\n`;
}
